import Foundation

enum NewFileType: Int, CaseIterable {
    case textDocument
    case zipArchive

    var menuTitle: String {
        switch self {
        case .textDocument: "New Text Document"
        case .zipArchive: "New Compressed (zipped) Folder"
        }
    }

    var fileExtension: String {
        switch self {
        case .textDocument: "txt"
        case .zipArchive: "zip"
        }
    }

    var initialContents: Data {
        switch self {
        case .textDocument: Data()
        case .zipArchive: Self.zipWithEmptyFolder
        }
    }

